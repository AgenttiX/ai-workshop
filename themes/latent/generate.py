#!/usr/bin/env python3
"""Generate the decorative SVG backgrounds of the latent theme.

The graphics are drawn procedurally with a fixed random seed, so running this script again
gives the same files. Edit the parameters below and rerun it to change them.

The graphics avoid SVG filters and masks (e.g. a Gaussian blur for a glow), since Chromium rasterizes them
when printing, which makes the PDF of the slides tens of megabytes. Glows are drawn as wide, faint strokes instead,
and the fade-out is computed into the opacity of each element.

- ``title.svg``: a layered neural network across the title slide, faded out behind the text.
- ``divider.svg``: the attention weights of two tokens to the previous tokens, as arcs above a row of tokens,
  with arrowheads pointing back to the attended tokens.
- ``corner.svg``: a small neural network for the top-right corner of the content slides.

Usage: ``python3 themes/latent/generate.py`` (only the standard library is needed)
"""

from collections.abc import Callable, Sequence
import itertools
import math
from pathlib import Path
import random

OUT_DIR = Path(__file__).parent
SEED = 2026
WIDTH = 1920
HEIGHT = 1080
CYAN = "#4fd1e8"
VIOLET = "#9b7bff"
INK = "#0b1020"
# Elements fainter than this are left out
MIN_OPACITY = 0.005

Point = tuple[float, float]
Fade = Callable[[float, float], float]


def no_fade(_x: float, _y: float) -> float:
    """Keep every element fully visible.

    :return: the opacity multiplier 1
    """
    return 1.0


def radial_fade(inner: float, outer: float, cy: float = HEIGHT / 2) -> Fade:
    """Create a fade-out towards the centre of the slide, where the text is.

    The distance is measured in units of half the width and half the height of the slide,
    so the faded area is an ellipse with the aspect ratio of the slide.

    :param inner: the distance within which the elements are hidden
    :param outer: the distance beyond which the elements are fully visible
    :param cy: vertical centre of the faded area
    :return: a function of the position that gives the opacity multiplier between 0 and 1
    """

    def fade(x: float, y: float) -> float:
        distance = math.hypot((x - WIDTH / 2) / (WIDTH / 2), (y - cy) / (HEIGHT / 2))
        return min(max((distance - inner) / (outer - inner), 0.0), 1.0)

    return fade


def svg_document(width: float, height: float, body: Sequence[str], defs: Sequence[str] = ()) -> str:
    """Wrap SVG elements into a complete SVG document.

    :param width: width of the viewBox
    :param height: height of the viewBox
    :param body: the SVG elements to draw
    :param defs: gradients, masks and filters referenced by the elements
    :return: the SVG document as a string
    """
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
        f'width="{width}" height="{height}" preserveAspectRatio="xMidYMid slice">',
        "<!-- Generated by themes/latent/generate.py, do not edit by hand -->",
    ]
    if defs:
        lines += ["<defs>", *defs, "</defs>"]
    lines += [*body, "</svg>", ""]
    return "\n".join(lines)


def layer_positions(
    counts: Sequence[int], x_min: float, x_max: float, y_mid: float, spacing: float
) -> list[list[Point]]:
    """Compute the node positions of a layered network.

    :param counts: number of nodes in each layer
    :param x_min: x coordinate of the first layer
    :param x_max: x coordinate of the last layer
    :param y_mid: vertical centre of the layers
    :param spacing: vertical distance between the nodes of a layer
    :return: the node positions, one list per layer
    """
    layers = []
    for i, count in enumerate(counts):
        x = x_min + (x_max - x_min) * i / (len(counts) - 1)
        layers.append([(x, y_mid + (j - (count - 1) / 2) * spacing) for j in range(count)])
    return layers


def network(
    rng: random.Random,
    layers: Sequence[Sequence[Point]],
    edge_probability: float,
    n_paths: int,
    edge_scale: float = 1.0,
    node_radius: float = 5.0,
    fade: Fade = no_fade,
) -> list[str]:
    """Draw a layered network: faint weighted edges, a few bright activation paths and the nodes.

    :param rng: random number generator
    :param layers: node positions of each layer, from :func:`layer_positions`
    :param edge_probability: probability that two nodes of adjacent layers are connected
    :param n_paths: number of highlighted paths from the first to the last layer
    :param edge_scale: multiplier of the line widths
    :param node_radius: radius of the nodes
    :param fade: opacity multiplier as a function of the position, see :func:`radial_fade`
    :return: the SVG elements
    """
    edges = ['<g stroke="url(#weights)" fill="none" stroke-linecap="round">']
    for left, right in itertools.pairwise(layers):
        for x1, y1 in left:
            for x2, y2 in right:
                if rng.random() > edge_probability:
                    continue
                # Most weights are small and a few are large, as in a trained network
                weight = rng.random() ** 3
                opacity = (0.06 + 0.3 * weight) * fade((x1 + x2) / 2, (y1 + y2) / 2)
                if opacity < MIN_OPACITY:
                    continue
                edges.append(
                    f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
                    f'stroke-width="{(0.6 + 2.2 * weight) * edge_scale:.2f}" '
                    f'stroke-opacity="{opacity:.3f}"/>'
                )
    edges.append("</g>")

    # Activation paths: one node per layer, drawn bright with a glow (a wide, faint stroke underneath)
    active: set[Point] = set()
    paths = ['<g stroke="url(#weights)" fill="none" stroke-linecap="round">']
    for _ in range(n_paths):
        points = [rng.choice(layer) for layer in layers]
        active.update(points)
        for (x1, y1), (x2, y2) in itertools.pairwise(points):
            visibility = fade((x1 + x2) / 2, (y1 + y2) / 2)
            if visibility < MIN_OPACITY:
                continue
            line = f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
            paths.append(line + f'stroke-width="{9 * edge_scale:.2f}" stroke-opacity="{0.12 * visibility:.3f}"/>')
            paths.append(line + f'stroke-width="{2.2 * edge_scale:.2f}" stroke-opacity="{0.75 * visibility:.3f}"/>')
    paths.append("</g>")

    return edges + paths + nodes(layers, active, edge_scale, node_radius, fade)


def nodes(
    layers: Sequence[Sequence[Point]], active: set[Point], edge_scale: float, node_radius: float, fade: Fade
) -> list[str]:
    """Draw the nodes of a layered network, the active ones filled and with a glow.

    :param layers: node positions of each layer
    :param active: the nodes on the activation paths
    :param edge_scale: multiplier of the line widths
    :param node_radius: radius of the nodes
    :param fade: opacity multiplier as a function of the position
    :return: the SVG elements
    """
    elements = ["<g>"]
    for layer in layers:
        for x, y in layer:
            visibility = fade(x, y)
            if visibility < MIN_OPACITY:
                continue
            if (x, y) in active:
                elements.append(
                    f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{node_radius * 2.6:.1f}" fill="url(#weights)" '
                    f'fill-opacity="{0.18 * visibility:.3f}"/>'
                )
                elements.append(
                    f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{node_radius * 1.3:.1f}" fill="url(#weights)" '
                    f'fill-opacity="{visibility:.3f}"/>'
                )
            else:
                elements.append(
                    f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{node_radius:.1f}" fill="{INK}" '
                    f'fill-opacity="{visibility:.3f}" stroke="url(#weights)" '
                    f'stroke-width="{1.5 * edge_scale:.2f}" stroke-opacity="{0.6 * visibility:.3f}"/>'
                )
    elements.append("</g>")
    return elements


def common_defs(width: float) -> list[str]:
    """Define the cyan-to-violet gradient.

    :param width: width of the drawing, over which the gradient runs
    :return: the SVG definitions
    """
    return [
        f'<linearGradient id="weights" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="{width}" y2="0">',
        f'<stop offset="0" stop-color="{CYAN}"/>',
        f'<stop offset="1" stop-color="{VIOLET}"/>',
        "</linearGradient>",
    ]


def title(rng: random.Random) -> str:
    """Draw a neural network across the whole title slide, faded out in the middle behind the text.

    :param rng: random number generator
    :return: the SVG document
    """
    layers = layer_positions([4, 7, 10, 12, 13, 12, 10, 7, 4], 90, WIDTH - 90, HEIGHT / 2, 76)
    # The network fades out where the title text is
    body = network(rng, layers, 0.5, 4, fade=radial_fade(0.45, 1.0, cy=0.48 * HEIGHT))
    return svg_document(WIDTH, HEIGHT, body, common_defs(WIDTH))


def softmax(logits: Sequence[float]) -> list[float]:
    """Normalize logits into probabilities, like the attention of a transformer.

    :param logits: unnormalized scores
    :return: probabilities that sum to one
    """
    peak = max(logits)
    exps = [math.exp(logit - peak) for logit in logits]
    total = sum(exps)
    return [e / total for e in exps]


def divider(rng: random.Random) -> str:
    """Draw a row of tokens along the bottom and the attention of two tokens to the previous ones.

    :param rng: random number generator
    :return: the SVG document
    """
    y_token = 968
    token_height = 30
    gap = 14
    x = 110.0
    tokens: list[tuple[float, float]] = []  # (x, width)
    while True:
        width = rng.choice([40, 56, 72, 88, 104, 128])
        if x + width > WIDTH - 110:
            break
        tokens.append((x, width))
        x += width + gap

    def centre(i: int) -> float:
        return tokens[i][0] + tokens[i][1] / 2

    body = []
    # Two attention heads: each query token attends to all previous tokens
    for query, colour in ((len(tokens) - 4, CYAN), (len(tokens) * 3 // 5, VIOLET)):
        logits = [rng.gauss(0, 1.3) for _ in range(query)]
        for i in rng.sample(range(query), 2):
            logits[i] += 3.5  # a couple of strongly attended tokens
        weights = softmax(logits)
        w_max = max(weights)
        body.append(f'<g fill="none" stroke="{colour}" stroke-linecap="round">')
        x_q = centre(query)
        for i, weight in enumerate(weights):
            w = weight / w_max
            x_k = centre(i)
            # Quadratic Bézier: the apex is half of the control point height above the tokens
            lift = min(0.55 * abs(x_q - x_k), 520)
            x_c, y_c = (x_q + x_k) / 2, y_token - lift
            stroke_width = 1 + 7 * w
            opacity = 0.08 + 0.6 * w
            # An arrowhead on the earlier token, along the tangent of the arc there.
            # The arc ends at the base of the arrowhead, so that its round cap doesn't poke out of the tip.
            length = 9 + 1.6 * stroke_width
            dx, dy = x_k - x_c, y_token - y_c
            norm = math.hypot(dx, dy)
            ux, uy = dx / norm, dy / norm
            x_b, y_b = x_k - length * ux, y_token - length * uy
            half = 0.45 * length
            body.append(
                f'<path d="M {x_q:.1f} {y_token:.1f} Q {x_c:.1f} {y_c:.1f} {x_b:.1f} {y_b:.1f}" '
                f'stroke-width="{stroke_width:.2f}" stroke-opacity="{opacity:.3f}"/>'
            )
            body.append(
                f'<path d="M {x_k:.1f} {y_token:.1f} L {x_b - half * uy:.1f} {y_b + half * ux:.1f} '
                f'L {x_b + half * uy:.1f} {y_b - half * ux:.1f} z" fill="{colour}" fill-opacity="{opacity:.3f}" '
                f'stroke="none"/>'
            )
        body.append("</g>")

    queries = {len(tokens) - 4: CYAN, len(tokens) * 3 // 5: VIOLET}
    body.append("<g>")
    for i, (x0, width) in enumerate(tokens):
        if i in queries:
            halo = 7
            body.append(
                f'<rect x="{x0 - halo:.1f}" y="{y_token - halo:.1f}" width="{width + 2 * halo}" '
                f'height="{token_height + 2 * halo}" rx="{7 + halo}" fill="{queries[i]}" fill-opacity="0.15"/>'
            )
            body.append(
                f'<rect x="{x0:.1f}" y="{y_token:.1f}" width="{width}" height="{token_height}" rx="7" '
                f'fill="{queries[i]}" fill-opacity="0.85"/>'
            )
        else:
            body.append(
                f'<rect x="{x0:.1f}" y="{y_token:.1f}" width="{width}" height="{token_height}" rx="7" '
                f'fill="{CYAN}" fill-opacity="0.06" stroke="{CYAN}" stroke-opacity="0.3" stroke-width="1.5"/>'
            )
    body.append("</g>")
    return svg_document(WIDTH, HEIGHT, body, common_defs(WIDTH))


def corner(rng: random.Random) -> str:
    """Draw a small neural network for the corner of the content slides.

    :param rng: random number generator
    :return: the SVG document
    """
    width, height = 240, 150
    layers = layer_positions([3, 5, 5, 2], 12, width - 12, height / 2, 30)
    body = network(rng, layers, 0.8, 1, edge_scale=0.8, node_radius=4.5)
    return svg_document(width, height, body, common_defs(width))


def main() -> None:
    """Write the SVG files next to this script."""
    rng = random.Random(SEED)
    for name, draw in (("title", title), ("divider", divider), ("corner", corner)):
        path = OUT_DIR / f"{name}.svg"
        path.write_text(draw(rng), encoding="utf-8")
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
